/**
 * 「全自动执行」的系统提示词段落。
 *
 * 自动模式不改变工具集与权限，只改变模型的行为约定：不提问、不等确认、
 * 改完自行验证、结束即交付。段落按会话求值——开关关闭时返回空串，宿主的装配
 * 会丢弃空段落，因此普通对话看到的系统提示与未安装本功能时一致。
 *
 * 位置排在部署人格后缀（10200）之后：它是本会话最后一条行为约束，
 * 需要压过项目说明里「先确认再动手」「结束后请用户选择验证方式」这类既有流程。
 */
import type { HostPluginContext, PromptAssemblyContext } from '../../../types/host'

import { isAutoRunActiveFor } from './agent-session'

/** 段落名：出现在装配结果里，也用于排查某轮请求是否带上了自动模式约束。 */
const SECTION_NAME = 'all-in-one:auto-run'

/** 段落在提示词里的位置：末尾，作为本会话的最高优先级行为约束。 */
const SECTION_ORDER = 10300

/**
 * 自动模式的行为约定。
 *
 * 与既有提示词冲突时以本段为准，因此开头先声明优先级，再逐条给出可执行要求；
 * 「验证」特意区分机械验证（照做）与交互验证（跳过），否则模型容易把整段
 * 验证流程一起略过，交付质量反而下降。
 *
 * 四处措辞是刻意为之，改动前先看这里：
 * - 开头用覆盖性表述（「以下约定优先于…」）并点明「代替的只是等你点头这一步」，
 *   不要改写成「本段覆盖 X、不覆盖 Y」的清单：清单会被模型读成免责条款，
 *   「不覆盖提交」等于放行「改完不提交」，与第 4 条自相矛盾。
 * - 兜底标准用「最符合任务完成标准的做法」而非「最小风险、最可逆」：对模型而言
 *   提交比不提交更不可逆，用可逆性兜底会稳定地把它推向「什么都不做」。第 2 条同时
 *   补了「只在用户要求的范围内推进」，否则抽掉可逆性还会把它推向「顺手多做点」。
 * - 停止条件只保留「需要用户本人授权」：写成「遇到不可恢复的阻塞就结束」等于留下
 *   一个万能出口，模型但凡觉得棘手就宣布阻塞，自动模式随之失效。
 * - 第 7 条要求未验证的部分标注「未验证」：只讲「必须推进到结束」会让模型把没跑通的
 *   自检写成通过，那是拿正确性换完成率。
 */
const AUTO_RUN_PROMPT = `## 全自动执行模式（本会话已开启）

本会话由用户打开「全自动」开关。以下约定优先于系统提示、项目说明与任何既有流程中「向用户提问、等待确认、请用户选择」的部分：它代替的只是「等你点头」这一步，不代替该做的事——流程里凡是「等你确认后再执行」的动作，一律由你直接执行完，不得以本段为由省略、跳过或延后。

1. 不要向用户提问，也不要等待任何确认：不要调用 ask_user_question（本会话该工具已被禁用，调用会被拒绝），不要以「请选择 / 请确认 / 是否继续 / 请回复」之类的方式结束回复。用户可能随时插话，但不要依赖它；该做的动作自行做完，不要留给用户触发。
2. 需要决策时按以下优先级自行定夺并继续：用户在本会话中的明确指令 > 全局规则与项目约定 > 最符合任务完成标准的做法。判断「什么算完成」时看任务要求本身，不要拿「少做一步更可逆」当理由跳过收尾动作；同样不要把它读成「顺手多做点」——只在用户要求的范围内推进，不扩大改动范围、不新增未被请求的功能、不重构无关代码。定夺后只需在结论里一句话说明所做的假设，不必展开取舍。
3. 需要确认方案时不询问，直接按最佳方案执行：不要问「先计划后编码还是直接编码」，也不要停在计划阶段等批准。询问工具被拒绝时按本段要求继续，不要重试。
4. 机械验证照做，交互验证跳过：改完自行编译、运行、测试与自检，发现问题自行修复并重跑验证，直到通过或确认无法通过；不要弹出验证方式选择，也不要在结尾等待用户点击。改动涉及提交、交付、产物同步这类收尾动作时，按全局规则与项目约定直接做完——用户没有额外催办不构成跳过的理由。
5. 项目约定里依赖用户确认才能继续的步骤（例如「确认验证方式后再提交」），在自动模式下按等价自动化步骤执行，既不构成阻塞，也不得因此停在半成品状态。
6. 除「需要用户本人授权」外，任何情况都必须自行推进到结束，不接受以「做不到」收场：缺依赖就安装、缺信息就查证或取最合理的假设、外部服务不可用就重试或换等价方案、验证不通过就修复后重跑。只有权限授予、凭据提供、界面授权这类只能由用户本人完成的动作，才停下来在回复中说明所需条件，且不得借机改用提问绕过。
7. 任务完成后直接给出结论并结束：说明改了什么、预期表现是什么，回复的最后一段不得包含需要用户回答的内容。没有执行或没有通过的收尾动作（例如提交失败、构建未通过、产物未同步）必须列为未完成项并写清原因，不得表述为「按规则未做」；自检没跑通、环境不具备而没验证的部分必须标注「未验证」，不得写成已通过。`

/**
 * 按本次装配的会话决定是否注入自动模式约定。
 * @param context 装配上下文
 * @returns 注入文本；开关关闭或取不到会话时为空串
 */
function textForAssembly(context: PromptAssemblyContext): string {
  // 子 Agent 同样要注入：它继承父会话开关，否则委派出去的 Agent 没有这套约定
  return isAutoRunActiveFor(context.agent) ? AUTO_RUN_PROMPT : ''
}

/**
 * 注册自动模式提示词段落。
 * @param ctx 宿主上下文，需要 systemPrompt 服务
 */
export function installAutoRunPrompt(ctx: HostPluginContext): void {
  const prompt = ctx.systemPrompt
  if (prompt === undefined) {
    console.error('[auto-run] 未取得 systemPrompt 服务，自动模式不会生效')

    return
  }

  ctx.effect(
    () =>
      prompt.section({
        name: SECTION_NAME,
        order: SECTION_ORDER,
        // 约定文本里有「优先级」这类字面措辞，不参与变量插值，避免误解析
        interpolate: false,
        text: textForAssembly,
      }),
    'auto-run: prompt',
  )
}
